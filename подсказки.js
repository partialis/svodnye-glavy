/* ═══════════════════════════════════════════════════════════════════════════
   ПОДСКАЗКИ НА ТЕРМИНЫ · всплывашка по наведению и по касанию

   Требование владельца дословно: «на пк достаточно навести курсор, кликать
   необязательно, хотя можно. На телефонах просто кликнуть для удобства.
   Закрыть можно крестиком. И чтобы можно было перейти на кнопку „подробнее“
   в сплывашке, если краткого объяснения не хватило и тебя перенесёт на другую
   страницу».

   ЧТО ВЗЯТО ГОТОВЫМ И ПОЧЕМУ ИМЕННО ЭТО (разведка 31.08):
   · Нативный атрибут `popover` — Baseline с апреля 2024 (Chrome 114+,
     Safari 17+, Firefox 125+). Он бесплатно даёт верхний слой без войн с
     z-index, закрытие по Escape, закрытие по клику снаружи и правильную
     доступность. Библиотека ради этого больше не нужна.
   · CSS Anchor Positioning НЕ берём: в Firefox он всё ещё не готов, и
     страница на нём разъехалась бы у части читателей. Позиционируем руками —
     это тридцать строк.
   · Tippy.js (14 КБ + Popper) рассматривался и отвергнут: он закрывает ровно
     то, что теперь умеет браузер, а тащить зависимость в файл, который
     открывают двойным щелчком, — лишнее.

   ВАЖНО ПРО file://. Страницы открываются с диска, а браузер в этом режиме
   блокирует fetch и ES-модули. Поэтому словарь терминов лежит НЕ в JSON,
   который надо подгрузить, а в обычном `термины.js` с глобальной переменной:
   `<script src>` работает с диска, `fetch` — нет. На этом ломается половина
   готовых движков, и это выяснилось до того, как мы на них оперлись.
   ═══════════════════════════════════════════════════════════════════════════ */

(function подсказки(){
  const СЛОВАРЬ = (typeof ТЕРМИНЫ !== "undefined" && ТЕРМИНЫ) || null;
  const статья = document.querySelector(".ob-article");
  if (!СЛОВАРЬ || !статья) return;

  const ЗАДЕРЖКА_ПОКАЗА = 170;   // чтобы подсказка не выпрыгивала при проводке мышью
  const ЗАДЕРЖКА_УХОДА = 260;    // чтобы успеть довести курсор до кнопки «подробнее»

  /* ─── разметка терминов в тексте ────────────────────────────────────────
     Подчёркивается ПЕРВОЕ вхождение термина в главе, как принято в
     справочниках: если помечать каждое, страница превращается в поле точек и
     подсказки перестают замечаться вовсе. */
  const ключи = Object.keys(СЛОВАРЬ).sort((а, б) => б.length - а.length);
  const занятые = new Set();

  /* Русский термин в тексте стоит в падеже, а в словаре — в именительном.
     Отрезаем окончание и разрешаем до трёх букв после основы: «фильтрация» →
     «фильтрац\w{0,3}» ловит фильтрации, фильтрацию, фильтрацией. Основу короче
     пяти букв не берём — на ней ловится половина словаря. */
  function образец(термин){
    const чистый = термин.trim();
    // АББРЕВИАТУРА ищется ТОЧНО И С УЧЁТОМ РЕГИСТРА. Иначе «ДО» (дыхательный
    // объём) ловит предлог «до», и в тексте появляется подчёркнутая ерунда —
    // ровно это и вылезло на первой же проверке. Падежей у аббревиатур нет,
    // поэтому основу тут наращивать не надо.
    if (/^[А-ЯЁA-Z][А-ЯЁA-Z0-9-]{0,7}$/u.test(чистый))
      return {ре: new RegExp("(?<![\\p{L}\\d-])" + экран(чистый) + "(?![\\p{L}\\d-])", "u")};

    const слова = чистый.split(/\s+/);
    const части = слова.map((с, i) => {
      const ч = с.replace(/[^\p{L}\p{N}-]/gu, "");
      if (i < слова.length - 1 || ч.length < 6) return экран(ч);
      return экран(ч.slice(0, ч.length - 2)) + "[а-яё]{0,3}";
    });
    // Короткое слово одним куском не размечаем вовсе: на трёх-четырёх буквах
    // ловится половина обычного текста.
    if (слова.length === 1 && чистый.length < 5) return null;
    return {ре: new RegExp("(?<![\\p{L}-])" + части.join("\\s+") + "(?![\\p{L}-])", "iu")};
  }
  const экран = с => с.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

  const образцы = ключи
        .map(к => ({ключ: к, о: образец(СЛОВАРЬ[к].форма || к)}))
        .filter(х => х.о)
        .map(х => ({ключ: х.ключ, ре: х.о.ре}));

  function пометить(){
    const обход = document.createTreeWalker(статья, NodeFilter.SHOW_TEXT, {
      acceptNode(узел){
        // Внутрь заголовков, ссылок, кода, подписей и уже помеченного не лезем:
        // подчёркнутый термин в заголовке выглядит как ошибка вёрстки.
        if (!узел.nodeValue || узел.nodeValue.trim().length < 4) return NodeFilter.FILTER_REJECT;
        if (узел.parentElement.closest("h1,h2,h3,h4,a,code,pre,figcaption,caption,th,.ob-term"))
          return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    const узлы = [];
    for (let у = обход.nextNode(); у; у = обход.nextNode()) узлы.push(у);

    for (const узел of узлы){
      for (const {ключ, ре} of образцы){
        if (занятые.has(ключ)) continue;
        const м = ре.exec(узел.nodeValue);
        if (!м) continue;
        занятые.add(ключ);
        const после = узел.splitText(м.index);
        после.splitText(м[0].length);
        const кн = document.createElement("button");
        кн.type = "button";
        кн.className = "ob-term";
        кн.textContent = м[0];
        кн.dataset.термин = ключ;
        кн.setAttribute("aria-label", м[0] + " — показать объяснение");
        после.replaceWith(кн);
        break;   // один термин на текстовый узел: иначе узлы разъезжаются под нами
      }
    }
  }
  пометить();

  const кнопки = [...статья.querySelectorAll(".ob-term")];
  if (!кнопки.length) return;

  /* ─── одна всплывашка на всю страницу ───────────────────────────────────
     Не по элементу на термин: сорок скрытых блоков в DOM ради того, что
     показывается по одному, — трата на пустом месте. */
  const окно = document.createElement("div");
  окно.className = "ob-pop";
  окно.popover = "auto";                       // сам даёт Escape и клик снаружи
  окно.innerHTML =
    '<button type="button" class="ob-pop-x" aria-label="Закрыть">×</button>' +
    '<div class="ob-pop-t"></div><div class="ob-pop-b"></div>' +
    '<a class="ob-pop-more" href="#">Подробнее →</a>';
  document.body.appendChild(окно);
  const эЗаг = окно.querySelector(".ob-pop-t");
  const эТек = окно.querySelector(".ob-pop-b");
  const эЕщё = окно.querySelector(".ob-pop-more");
  окно.querySelector(".ob-pop-x").addEventListener("click", () => закрыть(true));

  let текущая = null, таймерПоказа = 0, таймерУхода = 0;
  const касание = matchMedia("(hover: none)").matches;

  function поместить(кн){
    const к = кн.getBoundingClientRect();
    const о = окно.getBoundingClientRect();
    const зазор = 10;
    let верх = к.bottom + зазор;
    if (верх + о.height > innerHeight - 8 && к.top - о.height - зазор > 8)
      верх = к.top - о.height - зазор;      // не влезло снизу — показываем сверху
    let лево = к.left + к.width / 2 - о.width / 2;
    лево = Math.max(8, Math.min(лево, innerWidth - о.width - 8));
    окно.style.top = Math.max(8, верх) + "px";
    окно.style.left = лево + "px";
  }

  function открыть(кн){
    const з = СЛОВАРЬ[кн.dataset.термин];
    if (!з) return;
    эЗаг.textContent = з.имя || кн.dataset.термин;
    эТек.textContent = з.кратко || "";
    эЕщё.href = "глоссарий.html#" + (з.якорь || "");
    // Подпись кнопки возвращаем: всплывашка одна на страницу, и после сноски
    // на ней остаётся «К списку литературы».
    эЕщё.textContent = "Подробнее →";
    текущая = кн;
    try { окно.showPopover(); } catch (e) { окно.style.display = "block"; }
    поместить(кн);
  }

  function закрыть(сразу){
    clearTimeout(таймерУхода);
    const дело = () => {
      try { окно.hidePopover(); } catch (e) { окно.style.display = "none"; }
      текущая = null;
    };
    if (сразу) дело(); else таймерУхода = setTimeout(дело, ЗАДЕРЖКА_УХОДА);
  }

  /* ЗАКРЫТОЕ КРЕСТИКОМ НЕ ОТКРЫВАЕТСЯ САМО. Владелец 01.09: «нажимаю на
     крестик и не закрывается». Так и было: крестик прятал окно, но указатель
     оставался на термине, срабатывал mouseenter — и через полсекунды окно
     возвращалось. Со стороны это неотличимо от неработающей кнопки.
     Флаг снимается, когда указатель уходит с термина. */
  let подавить = null;
  окно.querySelector(".ob-pop-x").addEventListener("click", () => { подавить = текущая; });

  /* РЕЖИМ ОТКРЫТИЯ — выбор читателя. Он же: «я думаю, они в принципе должны
     открываться только когда на них кликают. Либо чтобы это можно было
     выбирать в настройках сайта». Взято второе: наведение удобно мышью,
     но мешает, когда читаешь и водишь курсором по строке. */
  const режим = () => {
    try { return localStorage.getItem("чтение-подсказки") || "navedenie"; }
    catch (e) { return "navedenie"; }
  };

  кнопки.forEach(кн => {
    // Клик работает ВСЕГДА, в любом режиме.
    кн.addEventListener("click", е => {
      е.preventDefault();
      подавить = null;
      if (текущая === кн) закрыть(true); else открыть(кн);
    });
    if (!касание){
      кн.addEventListener("mouseenter", () => {
        if (режим() !== "navedenie" || подавить === кн) return;
        clearTimeout(таймерУхода);
        таймерПоказа = setTimeout(() => открыть(кн), ЗАДЕРЖКА_ПОКАЗА);
      });
      кн.addEventListener("mouseleave", () => {
        clearTimeout(таймерПоказа);
        if (подавить === кн) подавить = null;
        if (режим() === "navedenie") закрыть(false);
      });
      кн.addEventListener("focus", () => { if (режим() === "navedenie") открыть(кн); });
    }
  });
  if (!касание){
    окно.addEventListener("mouseenter", () => clearTimeout(таймерУхода));
    окно.addEventListener("mouseleave", () => закрыть(false));
  }
  /* ─── превью источника у сноски ─────────────────────────────────────────
     Тот же приём, что у Википедии: наводишь на [1, с. ?] — видишь книгу, не
     прыгая в конец главы. Механика уже построена выше, поэтому цена добавки
     здесь — десяток строк, а не вторая всплывашка.

     Текст берётся ИЗ САМОГО СПИСКА литературы на странице, а не из отдельной
     таблицы: две копии одного разошлись бы на первой же правке списка. */
  document.querySelectorAll('sup > a[href^="#ist-"]').forEach(сс => {
    const цель = document.getElementById(decodeURIComponent(сс.getAttribute("href")).slice(1));
    if (!цель) return;
    const книга = цель.textContent.replace(/[↑\s]+$/, "").trim();
    const показать = () => {
      эЗаг.textContent = "Источник " + (сс.textContent.match(/\d+/) || [""])[0];
      эТек.textContent = книга;
      эЕщё.href = сс.getAttribute("href");
      эЕщё.textContent = "К списку литературы →";
      текущая = сс;
      try { окно.showPopover(); } catch (e) { окно.style.display = "block"; }
      поместить(сс);
    };
    сс.addEventListener("click", е => {
      // Клик оставляем ШТАТНЫМ переходом к списку: сноска — это ссылка, и
      // ломать её ради всплывашки нельзя, иначе она перестанет открываться в
      // новой вкладке и работать с клавиатуры как ссылка.
      if (касание) { е.preventDefault(); показать(); }
    });
    if (!касание){
      сс.addEventListener("mouseenter", () => {
        if (режим() !== "navedenie") return;
        clearTimeout(таймерУхода);
        таймерПоказа = setTimeout(показать, ЗАДЕРЖКА_ПОКАЗА);
      });
      сс.addEventListener("mouseleave", () => { clearTimeout(таймерПоказа); закрыть(false); });
    }
  });

  addEventListener("scroll", () => { if (текущая) поместить(текущая); }, {passive: true});
  addEventListener("resize", () => { if (текущая) поместить(текущая); });
})();
