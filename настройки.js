/* ═══════════════════════════════════════════════════════════════════════════
   НАСТРОЙКИ ЧТЕНИЯ

   Раньше это была чёрная полоса поверх каждой страницы. Дословный приговор:
   «вся эта плашка выше просто ужасная и некрасива, сбивает всю эстетику»,
   «настройка облика по типу Википедия и прочее должно быть отдельно в
   настройках», «там не должно быть разных вариантов облика, это не главы».

   Поэтому файл делает две разные вещи:

   1. НА ЛЮБОЙ странице — молча применяет сохранённый выбор (размер, ширина,
      шрифт). Ничего не рисует.
   2. НА СТРАНИЦЕ НАСТРОЕК — рисует органы управления в её текст.

   Слов-жаргонизмов нет: «Размер текста» с кнопками А− и А+ вместо «кегля»
   («слово кегль лишнее — просто должны быть две кнопки увеличения шрифта и
   уменьшения»), ширина колонки — тремя значками («колонки опять же значком
   сменить»).
   ═══════════════════════════════════════════════════════════════════════════ */

const НАСТРОЙКИ = (() => {
  const БЕРУ = (к, по) => { try { const з = localStorage.getItem(к); return з === null ? по : з; }
                            catch(e){ return по; } };
  const ДАЮ = (к, з) => { try { localStorage.setItem(к, з); } catch(e){} };

  const РАЗМЕРЫ = [0.85, 0.925, 1, 1.1, 1.22, 1.35];
  const ШИРИНЫ = [
    {к: "uzkaya",    т: "Узкая",   п: "Меньше знаков в строке — глаз реже промахивается мимо начала следующей"},
    {к: "obychnaya", т: "Обычная", п: "Ровно та, что снята с сайта, под который сделан облик"},
    {к: "shirokaya", т: "Широкая", п: "Больше текста на экран и меньше прокрутки"},
  ];
  const ШРИФТЫ = [
    {к: "",         т: "Как на сайте", стек: ""},
    {к: "grotesk",  т: "Гротеск",      стек: 'system-ui, "Segoe UI", Roboto, Arial, sans-serif'},
    {к: "serif",    т: "Засечный",     стек: 'Georgia, "Times New Roman", serif'},
    {к: "shirokiy", т: "Широкий",      стек: 'Verdana, Tahoma, "Segoe UI", sans-serif'},
  ];

  let размер = Number(БЕРУ("чтение-размер", "2"));

  function применитьРазмер(и, сохранять){
    размер = Math.max(0, Math.min(РАЗМЕРЫ.length - 1, и));
    document.documentElement.style.setProperty("--ob-zoom", String(РАЗМЕРЫ[размер]));
    if (сохранять !== false) ДАЮ("чтение-размер", String(размер));
  }
  function применитьШирину(к, сохранять){
    document.documentElement.setAttribute("data-shirina", к);
    if (сохранять !== false) ДАЮ("чтение-ширина", к);
    if (window.ОБЛИК && window.ОБЛИК.перекладка) requestAnimationFrame(window.ОБЛИК.перекладка);
  }
  function применитьШрифт(к, сохранять){
    const ш = ШРИФТЫ.find(х => х.к === к) || ШРИФТЫ[0];
    if (ш.стек) document.documentElement.style.setProperty("--ob-font", ш.стек);
    else document.documentElement.style.removeProperty("--ob-font");
    if (сохранять !== false) ДАЮ("чтение-шрифт", ш.к);
  }

  // Применяем СРАЗУ, на любой странице и до отрисовки органов управления.
  применитьРазмер(размер, false);
  применитьШирину(БЕРУ("чтение-ширина", "obychnaya"), false);
  применитьШрифт(БЕРУ("чтение-шрифт", ""), false);

  return {РАЗМЕРЫ, ШИРИНЫ, ШРИФТЫ, БЕРУ, ДАЮ,
          применитьРазмер, применитьШирину, применитьШрифт,
          размер: () => размер};
})();

/* ─── органы управления: только на странице настроек ──────────────────────*/
(function страницаНастроек(){
  const место = document.getElementById("настройки-тут");
  if (!место) return;

  const {РАЗМЕРЫ, ШИРИНЫ, ШРИФТЫ, БЕРУ} = НАСТРОЙКИ;
  const эл = (тег, кл, текст) => {
    const e = document.createElement(тег);
    if (кл) e.className = кл;
    if (текст != null) e.textContent = текст;
    return e;
  };
  const блок = (заголовок, пояснение) => {
    const б = эл("section", "ns-blok");
    б.appendChild(эл("h2", null, заголовок));
    if (пояснение) б.appendChild(эл("p", "ns-pod", пояснение));
    return б;
  };
  const отметить = (гнездо, значение) =>
    [...гнездо.querySelectorAll("button")].forEach(b =>
      b.setAttribute("aria-pressed", String(b.dataset.знач === значение)));

  /* размер */
  const б1 = блок("Размер текста", "Меняется во всех главах сразу и запоминается.");
  const ряд1 = эл("div", "ns-ryad");
  const меньше = эл("button", "ns-az", "А−");
  const число = эл("span", "ns-znach");
  const больше = эл("button", "ns-az ns-az-b", "А+");
  меньше.type = больше.type = "button";
  меньше.setAttribute("aria-label", "Уменьшить размер текста");
  больше.setAttribute("aria-label", "Увеличить размер текста");
  const показать = () => {
    число.textContent = Math.round(РАЗМЕРЫ[НАСТРОЙКИ.размер()] * 100) + "%";
    меньше.disabled = НАСТРОЙКИ.размер() === 0;
    больше.disabled = НАСТРОЙКИ.размер() === РАЗМЕРЫ.length - 1;
  };
  меньше.addEventListener("click", () => { НАСТРОЙКИ.применитьРазмер(НАСТРОЙКИ.размер() - 1); показать(); });
  больше.addEventListener("click", () => { НАСТРОЙКИ.применитьРазмер(НАСТРОЙКИ.размер() + 1); показать(); });
  ряд1.append(меньше, число, больше);
  б1.appendChild(ряд1);
  место.appendChild(б1);
  показать();

  /* ширина — значками */
  const б2 = блок("Ширина колонки");
  const ряд2 = эл("div", "ns-ryad");
  const подпись2 = эл("p", "ns-pod");
  ШИРИНЫ.forEach(ш => {
    const b = эл("button", "ns-znak");
    b.type = "button"; b.dataset.знач = ш.к; b.title = ш.т;
    b.setAttribute("aria-label", "Колонка: " + ш.т.toLowerCase());
    const доли = {uzkaya: [10, 6, 9], obychnaya: [16, 12, 15], shirokaya: [22, 18, 21]}[ш.к];
    b.innerHTML = '<svg viewBox="0 0 26 16" width="26" height="16" aria-hidden="true">' +
      доли.map((д, i) => '<rect x="' + ((26 - д) / 2) + '" y="' + (3 + i * 4) +
                         '" width="' + д + '" height="2" rx="1" fill="currentColor"/>').join("") +
      '</svg>';
    b.addEventListener("click", () => {
      НАСТРОЙКИ.применитьШирину(ш.к);
      подпись2.textContent = ш.т + " — " + ш.п;
      отметить(ряд2, ш.к);
    });
    ряд2.appendChild(b);
  });
  б2.append(ряд2, подпись2);
  место.appendChild(б2);
  const ш0 = ШИРИНЫ.find(х => х.к === БЕРУ("чтение-ширина", "obychnaya")) || ШИРИНЫ[1];
  подпись2.textContent = ш0.т + " — " + ш0.п;
  отметить(ряд2, ш0.к);

  /* шрифт */
  const б3 = блок("Шрифт", "«Как на сайте» — тот, что у выбранного облика.");
  const ряд3 = эл("div", "ns-ryad");
  ШРИФТЫ.forEach(ш => {
    const b = эл("button", "ns-knopka", ш.т);
    b.type = "button"; b.dataset.знач = ш.к;
    if (ш.стек) b.style.fontFamily = ш.стек;
    b.addEventListener("click", () => { НАСТРОЙКИ.применитьШрифт(ш.к); отметить(ряд3, ш.к); });
    ряд3.appendChild(b);
  });
  б3.appendChild(ряд3);
  место.appendChild(б3);
  отметить(ряд3, БЕРУ("чтение-шрифт", ""));

  /* облик */
  if (window.ОБЛИК) {
    const б4 = блок("Облик страницы",
      "Одиннадцать видов, снятых с настоящих учебных и справочных сайтов: " +
      "кегль, интерлиньяж, цвета и ширины взяты замером с живых страниц. " +
      "Гарнитуры у части сайтов платные, поэтому заменены ближайшими системными — " +
      "замена названа в описании каждого.");
    const сетка = эл("div", "ns-setka");
    const подпись4 = эл("p", "ns-pod");
    window.ОБЛИК.ОБЛИКИ.forEach((о, i) => {
      const b = эл("button", "ns-knopka", о.имя);
      b.type = "button"; b.dataset.знач = String(i);
      b.addEventListener("click", () => { window.ОБЛИК.применить(i); отметитьОблик(i); });
      сетка.appendChild(b);
    });
    function отметитьОблик(i){
      const о = window.ОБЛИК.ОБЛИКИ[i];
      отметить(сетка, String(i));
      подпись4.innerHTML = "<b>" + о.имя + "</b> · вид снят с <i>" + о.сайт + "</i> — " + о.чем;
    }
    б4.append(сетка, подпись4);
    место.appendChild(б4);
    отметитьОблик(window.ОБЛИК.текущий());
  }

  /* сброс */
  const низ = эл("div", "ns-niz");
  const сброс = эл("button", "ns-sbros", "Сбросить всё к исходному");
  сброс.type = "button";
  сброс.addEventListener("click", () => {
    НАСТРОЙКИ.применитьРазмер(2); показать();
    НАСТРОЙКИ.применитьШирину("obychnaya"); отметить(ряд2, "obychnaya");
    подпись2.textContent = ШИРИНЫ[1].т + " — " + ШИРИНЫ[1].п;
    НАСТРОЙКИ.применитьШрифт(""); отметить(ряд3, "");
    if (window.ОБЛИК) { window.ОБЛИК.применить(0); location.reload(); }
  });
  низ.appendChild(сброс);
  место.appendChild(низ);
})();
